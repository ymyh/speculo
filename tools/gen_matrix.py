"""Enumerate the value-class matrices used by tests/*.

Run: python tools/gen_matrix.py

Prints the expected-result tables that are pasted into
tests/method_test.cpp (invoke), tests/field_test.cpp (set) and
tests/class_test.cpp (lookup). Every cell of the cartesian product is produced
here, so no cell can be silently forgotten when the tables are maintained.

The precedence encoded below is the contract of api_design.md §0.1 and the
check order implemented in src/object.cppm; when one of them changes, change it
here first and re-paste the tables.
"""

RECEIVERS = ["Normal", "Const", "Volatile", "WrongType", "Null"]
ARGS = ["Match", "Empty", "Extra", "WrongType", "ConstForMutableRef"]
VALUES = ["Match", "Null", "WrongType", "ConstSource", "Boxed"]

OK = "Ok"


def invoke_cell(receiver, args):
    # Method::invoke (src/object.cppm:1017):
    # count -> receiver null -> receiver type -> const -> volatile -> arguments
    if args in ("Empty", "Extra"):
        return "InvalidArgument"
    if receiver == "Null":
        return "NullInstance"
    if receiver == "WrongType":
        return "TypeMismatch"
    if receiver == "Const":
        return "ReadOnly"
    if receiver == "Volatile":
        return "NotSupported"
    return OK if args == "Match" else "TypeMismatch"


def set_cell(receiver, value):
    # Field::set (src/object.cppm:665):
    # receiver null -> const -> receiver type -> volatile -> field writability
    # -> value null -> value type
    if receiver == "Null":
        return "NullInstance"
    if receiver == "Const":
        return "ReadOnly"
    if receiver == "WrongType":
        return "TypeMismatch"
    if receiver == "Volatile":
        return "NotSupported"
    return OK if value in ("Match", "ConstSource", "Boxed") else "TypeMismatch"


def emit_2d(name, rows, cols, cell):
    print(f"// {name}: {len(rows)} x {len(cols)} = {len(rows) * len(cols)} cells")
    for row in rows:
        expected = ", ".join(f"Expected::{cell(row, column)}" for column in cols)
        print(f"    /* {row:<9} */ {{ {expected} }},")
    print()


print("// Generated by tools/gen_matrix.py — do not edit by hand.\n")
emit_2d("Invoke", RECEIVERS, ARGS, invoke_cell)
emit_2d("FieldSet", RECEIVERS, VALUES, set_cell)

WAYS = ["ClassPtr", "TypeName", "Template", "TemplateName", "Declared"]
TARGETS = ["Match", "MissingName", "WrongParams", "WrongArity"]
print(f"// Lookup: {len(WAYS)} ways x {len(TARGETS)} targets = {len(WAYS) * len(TARGETS)} cells")
for way in WAYS:
    cells = "  ".join(f"{t}={'Ok' if t == 'Match' else 'NotFound'}" for t in TARGETS)
    print(f"// {way:<13} {cells}")

print(f"\n// totals: invoke {len(RECEIVERS) * len(ARGS)}, "
      f"set {len(RECEIVERS) * len(VALUES)}, lookup {len(WAYS) * len(TARGETS)}")
assert len(RECEIVERS) * len(ARGS) == 25
assert len(RECEIVERS) * len(VALUES) == 25
assert len(WAYS) * len(TARGETS) == 20
